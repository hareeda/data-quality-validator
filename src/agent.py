
import json
from collections import defaultdict
from pathlib import Path
from typing import TypedDict

from langgraph.graph import END, START, StateGraph
from ollama import chat

from src.validation import validate_companies


PROJECT_ROOT = Path(__file__).resolve().parent.parent
REPORT_PATH = PROJECT_ROOT / "reports" / "agent_quality_report.md"


class AgentState(TypedDict, total=False):
    input_path: str
    validation_report: dict
    evidence_summary: dict
    ai_insights: str
    ai_status: str
    final_report: str


def validate_data(state: AgentState) -> dict:
    """Run deterministic validation on the supplied or default CSV."""
    input_path = state.get("input_path")

    if input_path:
        report = validate_companies(input_path)
    else:
        report = validate_companies()

    return {"validation_report": report}


def build_evidence_summary(report: dict) -> dict:
    """Build rule-level evidence using Python, not the LLM."""
    grouped_findings = defaultdict(list)

    for issue in report.get("issues", []):
        rule = issue.get("rule", "unknown_rule")

        grouped_findings[rule].append({
            "company_id": issue.get("company_id"),
            "severity": issue.get("severity", "UNKNOWN"),
            "message": issue.get("message", ""),
        })

    rules = []

    for rule, findings in sorted(grouped_findings.items()):
        severity_counts = defaultdict(int)

        for finding in findings:
            severity_counts[finding["severity"]] += 1

        rules.append({
            "rule": rule,
            "finding_count": len(findings),
            "severity_breakdown": dict(sorted(severity_counts.items())),
            "evidence": findings[:5],
            "additional_findings_omitted": max(0, len(findings) - 5),
        })

    return {
        "verified_totals": {
            "total_records": report["total_records"],
            "total_issues": report["total_issues"],
            "affected_records": report["affected_records"],
        },
        "verified_severity_breakdown": report["issues_by_severity"],
        "verified_rule_breakdown": report["issues_by_rule"],
        "rule_evidence": rules,
    }


def build_fallback_insights(evidence: dict) -> str:
    """Generate a grounded report if the local LLM is unavailable."""
    lines = [
        "### Main data quality risks",
        "The validation engine identified the following rule-based findings:",
    ]

    rules = evidence["rule_evidence"]

    if not rules:
        lines.append(
            "- No validation findings were returned by the validation engine."
        )
    else:
        for item in rules:
            lines.append(
                f"- `{item['rule']}`: "
                f"{item['finding_count']} finding(s)."
            )

    lines.extend([
        "",
        "### Potential business impact",
        "Investigate findings before using the affected records for "
        "company profiling, reporting, or analytical decisions. The actual "
        "impact depends on the underlying records and their intended use.",
        "",
        "### Recommended investigation and corrective actions",
        "- Review the affected records and the evidence recorded for each rule.",
        "- Confirm suspected issues against authoritative source data.",
        "- Correct records only after verification and retain an audit trail.",
        "- Rerun validation after approved corrections.",
        "",
        "### Limitations and items requiring human review",
        "These are automated validation flags, not confirmed errors. "
        "The local LLM was unavailable, so this report uses a deterministic "
        "fallback rather than AI-generated analysis.",
    ])

    return "\n".join(lines)


def generate_insights(state: AgentState) -> dict:
    """Generate evidence-grounded insights with a safe fallback."""
    evidence = build_evidence_summary(state["validation_report"])

    
    prompt = f"""
You are a careful business data quality analyst.

The following JSON was generated by the Python validation engine.
Use it only to understand the validation rules and evidence:

{json.dumps(evidence, indent=2)}

Write a concise report with these sections:
1. Main data quality risks
2. Potential business impact
3. Recommended investigation and corrective actions
4. Limitations and items requiring human review

Strict requirements:
- Do not write ANY numerical counts, totals, ratios, percentages,
  record IDs, or calculated statistics in your narrative.
- Do not reproduce or summarize the numerical validation summary.
- Refer to findings by validation rule name or general category.
- Discuss only supplied validation rules and evidence.
- Do not claim that a flagged record is definitely wrong.
- Do not invent causes, company facts, financial losses, or outcomes.
- Explain potential impacts conditionally.
- Tie recommendations to the supplied validation rules.
- Recommend investigation before modifying source records.
- Do not claim that records have already been corrected.
- State when business impact cannot be determined from the evidence.
- Use clear business language and no more than 200 words.
"""


    try:
        response = chat(
            model="llama3.2:latest",
            messages=[
                {
                    "role": "system",
                    "content": (
                        "You explain data quality evidence conservatively. "
                        "Never invent findings, totals, causes, or outcomes. "
                        "Distinguish potential impact from verified impact."
                    ),
                },
                {"role": "user", "content": prompt},
            ],
            options={"temperature": 0.1},
        )

        insights = response["message"]["content"].strip()

        if not insights:
            raise ValueError("The local model returned an empty response.")

        return {
            "evidence_summary": evidence,
            "ai_insights": insights,
            "ai_status": "success",
        }

    except Exception as exc:
        print(f"Local AI insight generation failed: {exc}")

        return {
            "evidence_summary": evidence,
            "ai_insights": build_fallback_insights(evidence),
            "ai_status": "fallback",
        }


def save_report(state: AgentState) -> dict:
    """Save verified statistics separately from generated explanations."""
    report = state["validation_report"]

    verified_summary = {
        "total_records": report["total_records"],
        "total_issues": report["total_issues"],
        "affected_records": report["affected_records"],
        "issues_by_severity": report["issues_by_severity"],
        "issues_by_rule": report["issues_by_rule"],
    }

    summary_json = json.dumps(verified_summary, indent=2)
    evidence_json = json.dumps(
        state["evidence_summary"], indent=2
    )

    ai_status = state.get("ai_status", "unknown")
    report_source = (
        "Local Ollama model"
        if ai_status == "success"
        else "Deterministic fallback; local AI unavailable"
    )

    final_report = (
        "# AI-Powered Business Data Quality Report\n\n"
        "## Verified Validation Summary\n\n"
        "These statistics were calculated by Python using the "
        "configured validation rules.\n\n"
        f"```json\n{summary_json}\n```\n\n"
        "## Rule-Level Evidence\n\n"
        "The following evidence was grouped by Python from the "
        "validation findings.\n\n"
        f"```json\n{evidence_json}\n```\n\n"
        "## Business Insights\n\n"
        f"Report source: **{report_source}**\n\n"
        f"{state['ai_insights']}\n\n"
        "---\n\n"
        "**Important:** Findings are rule-based flags, not necessarily "
        "confirmed errors. The validation engine calculates the statistics; "
        "the language model, when available, explains the supplied evidence. "
        "Review findings before changing source data.\n"
    )

    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(final_report, encoding="utf-8")

    print(f"Report saved to: {REPORT_PATH}")

    return {"final_report": final_report}


builder = StateGraph(AgentState)

builder.add_node("validate_data", validate_data)
builder.add_node("generate_insights", generate_insights)
builder.add_node("save_report", save_report)

builder.add_edge(START, "validate_data")
builder.add_edge("validate_data", "generate_insights")
builder.add_edge("generate_insights", "save_report")
builder.add_edge("save_report", END)

agent = builder.compile()


if __name__ == "__main__":
    result = agent.invoke({})

    print(result["final_report"])
    print(f"\nAI status: {result.get('ai_status', 'unknown')}")
    print("LangGraph workflow completed successfully.")
